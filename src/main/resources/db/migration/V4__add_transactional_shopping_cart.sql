SET ROLE northstar_owner;

CREATE TABLE northstar.customer (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY,
    email varchar(254) NOT NULL,
    display_name varchar(120) NOT NULL,
    CONSTRAINT customer_pk PRIMARY KEY (customer_id),
    CONSTRAINT customer_email_unique UNIQUE (email),
    CONSTRAINT customer_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT customer_display_name_not_blank CHECK (btrim(display_name) <> '')
);

CREATE TABLE northstar.shopping_cart (
    cart_id bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id bigint NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    total_quantity integer NOT NULL DEFAULT 0,
    CONSTRAINT shopping_cart_pk PRIMARY KEY (cart_id),
    CONSTRAINT shopping_cart_customer_unique UNIQUE (customer_id),
    CONSTRAINT shopping_cart_customer_fk FOREIGN KEY (customer_id)
        REFERENCES northstar.customer (customer_id),
    CONSTRAINT shopping_cart_version_nonnegative CHECK (version >= 0),
    CONSTRAINT shopping_cart_total_quantity_range CHECK (total_quantity BETWEEN 0 AND 20)
);

CREATE TABLE northstar.cart_item (
    cart_item_id bigint GENERATED BY DEFAULT AS IDENTITY,
    cart_id bigint NOT NULL,
    product_id bigint NOT NULL,
    quantity integer NOT NULL,
    CONSTRAINT cart_item_pk PRIMARY KEY (cart_item_id),
    CONSTRAINT cart_item_cart_product_unique UNIQUE (cart_id, product_id),
    CONSTRAINT cart_item_cart_fk FOREIGN KEY (cart_id)
        REFERENCES northstar.shopping_cart (cart_id) ON DELETE CASCADE,
    CONSTRAINT cart_item_product_fk FOREIGN KEY (product_id)
        REFERENCES northstar.product (product_id),
    CONSTRAINT cart_item_quantity_range CHECK (quantity BETWEEN 1 AND 10)
);

